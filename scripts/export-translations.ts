/**
 * EVERY RUSSIAN OR UKRAINIAN LINE THE APP HOLDS, IN ONE FILE PER LANGUAGE, FOR
 * SOMEBODY FLUENT TO READ.
 *
 *   npx tsx scripts/export-translations.ts
 *
 * writes `docs/translations/ru.md` and `docs/translations/uk.md`. Each line is
 * printed beside the English it translates, grouped by the area of the app it
 * belongs to, with a box to tick, so a reviewer can work through a language
 * in one pass and say which lines they changed. Regenerate it after any
 * translation lands; the file is a reading of the tables, never edited by
 * hand, and a fix goes into the area file under `lib/copy/i18n/` it names.
 *
 *   npx tsx scripts/export-translations.ts --since <git ref> --out <directory>
 *
 * writes only the lines that are new or changed since that ref, one file per
 * language in the same shape, into the directory named, and leaves
 * `docs/translations/` alone. The earlier table is the generated file at the
 * ref (`lib/copy/i18n/generated/`); a ref that has none lists every line as new
 * and says so.
 *
 *   npx tsx scripts/export-translations.ts --csv [--since <git ref>] [--out <directory>]
 *
 * writes the same lines as a sheet, `ru.csv` and `uk.csv`, into the directory
 * named (`translation-review/` by default, which nothing commits): one row per
 * line with its exact area key, the English, the translation, and `ok`,
 * `correction` and `why` left empty for the reader.
 * `npm run apply:translation-review -- ru.csv` reads a filled one back. The English for each line is found by walking the areas and
 * hashing each key with `lineKey`, since a key is a hash and never inverted.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { AREAS } from "@/lib/copy/i18n";
import { changedLines } from "@/lib/copy/i18n/changed";
import { keyOf, lineKey } from "@/lib/copy/i18n/table";
import { ENTRY_COPY } from "@/lib/copy/entryLocales";
import { MACHINE_NOTICE, MACHINE_NOTICE_EN, MACHINE_SHORT } from "@/lib/copy/locale";
import { COUNTED_CORE } from "@/lib/copy/i18n/counted";
import { translationSheet } from "@/lib/review/translationSheet";
import { csvCell } from "./lib/csv";

type L = "ru" | "uk";
const NAMES: Record<L, string> = { ru: "Russian", uk: "Ukrainian" };

/** A line set off so Markdown cannot read it as anything but text. */
function quote(text: string): string {
  return text.replace(/\r?\n/g, " ").replace(/([\\`*_<>[\]#|])/g, "\\$1");
}

function areaFile(name: string): string {
  return name === "core" ? `lib/copy/i18n/${"{ru,uk}"}.ts` : `lib/copy/i18n/areas/${name}.ts`;
}

function strings(value: unknown, path: string, out: [string, string][]): void {
  if (typeof value === "string") out.push([path, value]);
  else if (Array.isArray(value)) value.forEach((v, i) => strings(v, `${path}[${i}]`, out));
  else if (value && typeof value === "object") {
    for (const [k, v] of Object.entries(value)) strings(v, path ? `${path}.${k}` : k, out);
  }
}

function build(locale: L): { text: string; lines: number } {
  const parts: string[] = [];
  let n = 0;
  const item = (english: string, translated: string, note?: string) => {
    n += 1;
    parts.push(`- [ ] **${n}.** ${quote(english)}${note ? ` _(${note})_` : ""}  \n  → ${quote(translated)}`);
  };

  parts.push(`# Kodukeel in ${NAMES[locale]}: every line to verify`, "");
  parts.push(
    "Generated by `npx tsx scripts/export-translations.ts` from the translation tables. Do not edit this file;",
    "fix a line in the file named under its heading and regenerate. Each entry is the English the app shows,",
    "then the translation. Tick a box when a line is right as it stands, and note the number of any line you change.",
    "",
    "Things that look odd and are deliberate:",
    "",
    "- `{name}` in braces is a value the app fills in (a number, a word, a date). It must stay, spelled exactly.",
    "- `{e1}`, `{e2}` stand for an Estonian word the app puts back unchanged; the table may not hold Estonian letters.",
    "- _(context: …)_ marks an English word that means two things on two screens and has a translation for each.",
    "- Estonian words (case names like seesütlev, forms like tuba) are never translated.",
    "",
  );

  parts.push("## The notice that the translation is unreviewed", "", "_lib/copy/locale.ts_", "");
  item(MACHINE_NOTICE_EN, MACHINE_NOTICE[locale]);
  item(MACHINE_NOTICE_EN, MACHINE_SHORT[locale], "short version");
  parts.push("");

  const entry = ENTRY_COPY[locale];
  const english: [string, string][] = [];
  strings(entry, "", english);
  parts.push("## The entry page for new visitors", "", "_lib/copy/entryLocales.ts (no English key: the line is shown beside its field name)_", "");
  for (const [path, value] of english) {
    if (path === "href" || path === "name" || path === "lang") continue;
    item(path, value, "field");
  }
  parts.push("");

  parts.push("## Counted words shared by every screen: one, few (2 to 4), many (5 and up)", "", "_lib/copy/locale.ts_", "");
  for (const [noun, forms] of Object.entries(COUNTED_CORE)) item(`${noun} / ${forms.en.join(", ")}`, forms[locale].join(", "), "1, 2, 5");
  parts.push("");

  for (const [name, area] of AREAS) {
    const rows = Object.entries(area[locale]);
    const counted = Object.entries(area.counted ?? {});
    if (rows.length === 0 && counted.length === 0) continue;
    parts.push(`## ${name} (${rows.length} lines)`, "", `_${areaFile(name)}_`, "");
    for (const [key, value] of rows) {
      const at = key.lastIndexOf("@");
      const hasContext = at > 0 && !key.slice(at + 1).includes(" ");
      if (hasContext) item(key.slice(0, at), value, `context: ${key.slice(at + 1)}`);
      else item(key, value);
    }
    if (counted.length > 0) {
      parts.push("", `### Counted words in ${name}: one, few (2 to 4), many (5 and up)`, "");
      for (const [noun, forms] of counted) item(`${noun} / ${forms.en.join(", ")}`, forms[locale].join(", "), "1, 2, 5");
    }
    parts.push("");
  }
  return { text: parts.join("\n") + "\n", lines: n };
}

/** A flag's value, or null where it was not given. */
function arg(name: string): string | null {
  const at = process.argv.indexOf(name);
  if (at < 0) return null;
  const value = process.argv[at + 1];
  if (!value || value.startsWith("--")) throw new Error(`${name} needs a value`);
  return value;
}

/** The generated table's lines at a git ref, or null where the ref has no such file. */
function linesAt(ref: string, locale: L): Record<string, string> | null {
  try {
    const text = execFileSync("git", ["show", `${ref}:lib/copy/i18n/generated/${locale}.json`], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      maxBuffer: 64 * 1024 * 1024,
    });
    return (JSON.parse(text) as { lines: Record<string, string> }).lines;
  } catch {
    return null;
  }
}

/** Every area line by its packed key: which area, the English, and any context. */
function englishByKey(locale: L): Map<string, { area: string; english: string; context: string | null; at: number }> {
  const out = new Map<string, { area: string; english: string; context: string | null; at: number }>();
  for (const [name, area] of AREAS) {
    for (const key of Object.keys(area[locale])) {
      const at = key.lastIndexOf("@");
      const hasContext = at > 0 && !key.slice(at + 1).includes(" ");
      out.set(lineKey(keyOf(key)), {
        area: name,
        english: hasContext ? key.slice(0, at) : key,
        context: hasContext ? key.slice(at + 1) : null,
        at: out.size,
      });
    }
  }
  return out;
}

function buildSince(locale: L, ref: string): { text: string; lines: number } {
  const now = (JSON.parse(readFileSync(`lib/copy/i18n/generated/${locale}.json`, "utf8")) as {
    lines: Record<string, string>;
  }).lines;
  const before = linesAt(ref, locale);
  const { added, changed } = changedLines(before ?? {}, now);
  const isChanged = new Set(changed);
  const english = englishByKey(locale);

  const byArea = new Map<string, { key: string; english: string; context: string | null; at: number }[]>();
  for (const key of [...added, ...changed]) {
    const found = english.get(key);
    const area = found?.area ?? "not found in any area";
    const list = byArea.get(area) ?? [];
    list.push({ key, english: found?.english ?? `(key ${key})`, context: found?.context ?? null, at: found?.at ?? Infinity });
    byArea.set(area, list);
  }

  const parts: string[] = [];
  let n = 0;
  parts.push(`# Kodukeel in ${NAMES[locale]}: lines new or changed since ${quote(ref)}`, "");
  parts.push(
    `Generated by \`npx tsx scripts/export-translations.ts --since ${quote(ref)}\`. Do not edit this file;`,
    "fix a line in the file named under its heading and run `npm run i18n:tables`. Each entry is the English the app",
    "shows, then the translation. Tick a box when a line is right as it stands, and note the number of any line you change.",
    "",
  );
  if (before === null) {
    parts.push(`The ref ${quote(ref)} holds no generated table for this language, so every line is listed as new.`, "");
  }
  if (added.length + changed.length === 0) parts.push("No line is new or changed.", "");

  const order = AREAS.map(([name]) => name);
  const areas = [...byArea.keys()].sort((a, b) => {
    const ia = order.indexOf(a), ib = order.indexOf(b);
    return (ia < 0 ? order.length : ia) - (ib < 0 ? order.length : ib);
  });
  for (const area of areas) {
    // In the order the area file holds them, which is the order a reviewer can find them in.
    const list = byArea.get(area)!.sort((a, b) => a.at - b.at);
    parts.push(`## ${area} (${list.length} lines)`, "", order.includes(area) ? `_${areaFile(area)}_` : "", "");
    for (const line of list) {
      n += 1;
      const notes = [isChanged.has(line.key) ? "changed" : "new", line.context ? `context: ${line.context}` : null]
        .filter(Boolean)
        .join(", ");
      parts.push(`- [ ] **${n}.** ${quote(line.english)} _(${notes})_  \n  → ${quote(now[line.key]!)}`);
    }
    parts.push("");
  }
  return { text: parts.join("\n") + "\n", lines: n };
}

const since = arg("--since");
const outDir = arg("--out");

if (process.argv.includes("--csv")) {
  const dir = outDir ?? "translation-review";
  mkdirSync(dir, { recursive: true });
  for (const locale of ["ru", "uk"] as const) {
    let rows = translationSheet(locale, AREAS);
    if (since !== null) {
      const now = (JSON.parse(readFileSync(`lib/copy/i18n/generated/${locale}.json`, "utf8")) as { lines: Record<string, string> }).lines;
      const { added, changed } = changedLines(linesAt(since, locale) ?? {}, now);
      const moved = new Set([...added, ...changed]);
      rows = [rows[0]!, ...rows.slice(1).filter((r) => moved.has(lineKey(keyOf(r[2]!))))];
    }
    const file = join(dir, `${locale}.csv`);
    writeFileSync(file, "\uFEFF" + rows.map((r) => r.map(csvCell).join(",")).join("\n") + "\n");
    console.log(`${file}: ${rows.length - 1} lines${since !== null ? ` new or changed since ${since}` : ""}`);
  }
} else if (since === null) {
  if (outDir !== null) throw new Error("--out goes with --since; without it the files are docs/translations/");
  mkdirSync("docs/translations", { recursive: true });
  for (const locale of ["ru", "uk"] as const) {
    const { text, lines } = build(locale);
    writeFileSync(`docs/translations/${locale}.md`, text);
    console.log(`docs/translations/${locale}.md: ${lines} lines`);
  }
} else {
  const dir = outDir ?? join("docs", "translations", "since");
  mkdirSync(dir, { recursive: true });
  for (const locale of ["ru", "uk"] as const) {
    const { text, lines } = buildSince(locale, since);
    const file = join(dir, `${locale}.md`);
    writeFileSync(file, text);
    console.log(`${file}: ${lines} lines new or changed since ${since}`);
  }
}
