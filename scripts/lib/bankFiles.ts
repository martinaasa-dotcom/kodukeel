/**
 * HOW THE BANK IS WRITTEN: one file per scene under `lib/scenes/bank/`, and
 * `lib/scenes/bank.ts` as the list of them.
 *
 * It was one file, and with a scene a pull request every one of them added
 * rows to it and conflicted with every other. Each scene's rows are its own
 * file now, written in the shape the single file had, and `BANK` is their
 * concatenation in scene order, so its shape and its order are what they were.
 * `scripts/draft-lines.ts` writes through here; a line typed in a session goes
 * into its scene's file by hand, in the same shape, with `model: "authored"`.
 */
import { readdirSync, unlinkSync, writeFileSync } from "node:fs";
import type { ScriptedLine } from "../../lib/scenes/scripted";

export const BANK_DIR = "lib/scenes/bank";
export const BANK_INDEX = "lib/scenes/bank.ts";

const HEADER = [
  "/* GENERATED by scripts/draft-lines.ts. Do not add a line by hand.",
  "",
  "   Every row was drafted by a model inside its scene's closed word list, passed",
  "   the four checks in lib/scenes/gate.ts on the day named, and was read in the",
  "   pull request that added it, by the native Estonian speaker who develops",
  "   this app. Regenerate with `npm run draft:lines`; the script keeps rows",
  "   that are already here and only drafts what is missing. A row",
  "   whose model is `authored` was typed in a session rather than drafted, and",
  "   went through the same checks on its way in; a beat named `hurdle:<id>` is",
  "   a curveball's line; a row carrying `level` was drafted for that band with",
  "   the band's pitch in front of the model, and a row carrying none is the net",
  "   under every band, read after the band's own and before a plainer band's;",
  "   a row carrying `about` names the beat a curveball's line is about, and the",
  "   curveball stands only straight after one (lib/scenes/scripted.ts is what",
  "   reads this; ADR-025 amendment 1.) */",
];

/** A scene id as a name an import can bind: `poodi-piima` is `poodiPiima`. */
export function bindingFor(sceneId: string): string {
  return sceneId.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

/** One row per line, so a diff reads as lines added rather than a file rewritten. */
function row(line: ScriptedLine): string {
  return `  { scene: ${JSON.stringify(line.scene)}, beat: ${JSON.stringify(line.beat)}, text: ${JSON.stringify(line.text)},`
    + ` model: ${JSON.stringify(line.model)}, draftedAt: ${JSON.stringify(line.draftedAt)}`
    + (line.level ? `, level: ${JSON.stringify(line.level)}` : "")
    + (line.about ? `, about: ${JSON.stringify(line.about)}` : "") + " },";
}

/** Every file the bank is, keyed by path, for rows already sorted the way the drafter sorts them. */
export function renderBank(rows: readonly ScriptedLine[]): Map<string, string> {
  const scenes: string[] = [];
  const byScene = new Map<string, ScriptedLine[]>();
  for (const line of rows) {
    if (!byScene.has(line.scene)) { byScene.set(line.scene, []); scenes.push(line.scene); }
    byScene.get(line.scene)!.push(line);
  }
  const files = new Map<string, string>();
  for (const scene of scenes) {
    files.set(`${BANK_DIR}/${scene}.ts`, [
      ...HEADER,
      'import type { ScriptedLine } from "../scripted";',
      "",
      `/** The prepared lines of \`${scene}\`. */`,
      "const LINES: readonly ScriptedLine[] = [",
      ...byScene.get(scene)!.map(row),
      "];",
      "",
      "export default LINES;",
      "",
    ].join("\n"));
  }
  files.set(BANK_INDEX, [
    ...HEADER,
    'import type { ScriptedLine } from "./scripted";',
    ...scenes.map((scene) => `import ${bindingFor(scene)} from "./bank/${scene}";`),
    "",
    "/** Every scene's prepared lines, one file a scene under `lib/scenes/bank/`, in scene order. */",
    "export const BANK: readonly ScriptedLine[] = [",
    ...scenes.map((scene) => `  ...${bindingFor(scene)},`),
    "];",
    "",
  ].join("\n"));
  return files;
}

/** Writes the bank, and removes the file of a scene that no longer has a row. */
export function writeBank(rows: readonly ScriptedLine[]): void {
  const files = renderBank(rows);
  for (const name of readdirSync(BANK_DIR, { withFileTypes: true })) {
    const path = `${BANK_DIR}/${name.name}`;
    if (name.isFile() && name.name.endsWith(".ts") && !files.has(path)) unlinkSync(path);
  }
  for (const [path, text] of files) writeFileSync(path, text);
}
