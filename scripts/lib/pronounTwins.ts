import { SUBJECT_PRONOUN } from "@/lib/scenes/lexicon";

/** An entry as this needs to read it, which `shippedDictionary` returns. */
export interface TwinSource {
  readonly lemma: string;
  /** The entry's CEFR band, which says whether a headword spelled like a short form is one a learner means. */
  readonly cefr: string | null;
  readonly extraForms: readonly { code: string; value: string }[];
}

/** One form of a personal pronoun recorded twice under one code: the long spelling and the short one. */
export interface PronounTwin {
  readonly lemma: string;
  readonly code: string;
  readonly long: string;
  readonly short: string;
}

/**
 * The pairs Ekilex records for the six personal pronouns (`SUBJECT_PRONOUN`):
 * two values under one morph code, the longer one first.
 *
 * A short spelling that is also a graded headword of its own is left out,
 * because a learner typing it most likely means that word: `must` is the
 * elative of `mina` and the word for black, `taga` the comitative of `tema`
 * and the word for behind, both A1. An ungraded headword is the tail of the
 * dictionary (`mulle`, an embankment, beside `mulle`, to me) and does not.
 * Nothing here is typed: every value is the dictionary's.
 */
export function pronounTwinsFrom(entries: readonly TwinSource[]): PronounTwin[] {
  const headwords = new Set(entries.filter((e) => e.cefr !== null).map((e) => e.lemma.toLowerCase()));
  const out: PronounTwin[] = [];
  for (const lemma of Object.keys(SUBJECT_PRONOUN)) {
    const entry = entries.find((e) => e.lemma === lemma);
    if (!entry) continue;
    const byCode = new Map<string, string[]>();
    for (const form of entry.extraForms) {
      const list = byCode.get(form.code) ?? [];
      if (!list.includes(form.value)) list.push(form.value);
      byCode.set(form.code, list);
    }
    for (const [code, values] of byCode) {
      if (values.length !== 2) continue;
      const [long, short] = [...values].sort((a, b) => b.length - a.length) as [string, string];
      if (long === short || headwords.has(short.toLowerCase())) continue;
      out.push({ lemma, code, long: long.toLowerCase(), short: short.toLowerCase() });
    }
  }
  return out;
}

/** The generated module, as `scripts/build-pronoun-twins.ts` writes it. */
export function renderTwins(twins: readonly PronounTwin[]): string {
  const rows = twins.map((t) => `  { lemma: ${JSON.stringify(t.lemma)}, code: ${JSON.stringify(t.code)}, long: ${JSON.stringify(t.long)}, short: ${JSON.stringify(t.short)} },`);
  return [
    "// Generated by scripts/build-pronoun-twins.ts from the dictionary's stored forms. Do not edit.",
    "// The long and short spellings of the six personal pronouns, which the lesson marker takes as one word.",
    "",
    "export interface PronounTwin { readonly lemma: string; readonly code: string; readonly long: string; readonly short: string }",
    "",
    "export const PRONOUN_TWINS: readonly PronounTwin[] = [",
    ...rows,
    "];",
    "",
  ].join("\n");
}
