/**
 * A2, LESSONS 1 TO 7: KELLE OMA? (docs/43-lessons.md §9.1).
 *
 * A2 is built on one idea, and this part teaches it: every word comes with an
 * [omastav] (2nd form), and the omastav is the stem every other ending goes
 * on. It opens on what the omastav says on its own, whose a thing is and
 * which one it is, then where things stand (`laua peal`), when (`pärast
 * tööd`), the dates, and the details a form asks for, and it ends at a
 * library desk where all of it is needed at once.
 *
 * A noun's omastav is taught as a `stem` form, so that from part two on, once
 * a lesson has explained an ending, the ledger covers that ending on every
 * stem taught (`ledger.ts`). Nothing here explains an ending yet: the
 * `Tallinnas` and `toas` of A1 are named for what they are, words built on
 * an omastav, and explained in lesson 8.
 *
 * Read by the native speaker in the pull request that adds it, and held to
 * the same two checks as every lesson (`lessons.test.ts`, `ledger.ts`).
 */

