import { z } from "zod";

import { API_VERSION, SHIPPED_ROUTES, routeKey, type RouteSpec } from "./contract";
import { DRAFT_ROUTES } from "./draft";
import { ApiErrorBody, API_ERROR_CODES, API_ERROR_STATUS } from "./errors";
import { BUILD_HEADER } from "./build";

/**
 * THE PUBLISHED SCHEMA, BUILT FROM THE ZOD SCHEMAS AND NOTHING ELSE.
 *
 * `npm run api:schema` writes this to `public/api/v1.schema.json`, and a unit
 * test fails when the committed file is not what this would write, so the file
 * a native developer reads cannot drift from the schemas a route parses with.
 *
 * A response is published open: `additionalProperties: false` is taken off
 * every object, because within v1 a response may gain a field and a client that
 * refused an unknown one would break on the first widening. A request keeps
 * what zod writes, since the server strips what it does not know anyway.
 */
type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

export interface PublishedRoute {
  method: string;
  path: string;
  auth: boolean;
  draft: boolean;
  item: string;
  summary: string;
  example: string;
  contentType: string;
  query?: Json;
  request?: Json;
  response?: Json;
}

export interface PublishedSchema {
  $comment: string;
  version: number;
  buildHeader: string;
  errors: { codes: Record<string, number>; body: Json };
  routes: Record<string, PublishedRoute>;
}

/** Every object in a schema left open to fields it does not name. */
function opened(node: Json): Json {
  if (Array.isArray(node)) return node.map(opened);
  if (node && typeof node === "object") {
    const out: { [key: string]: Json } = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === "additionalProperties" && value === false) continue;
      out[key] = opened(value);
    }
    return out;
  }
  return node;
}

function withoutDialect(node: Json): Json {
  if (node && typeof node === "object" && !Array.isArray(node)) {
    const { $schema: _dialect, ...rest } = node;
    return rest;
  }
  return node;
}

/** One zod schema as JSON Schema, in the direction it travels. */
export function jsonSchemaOf(schema: z.ZodType, io: "input" | "output"): Json {
  const raw = z.toJSONSchema(schema, { io, unrepresentable: "any" }) as Json;
  return withoutDialect(io === "output" ? opened(raw) : raw);
}

function publish(route: RouteSpec, draft: boolean): PublishedRoute {
  const out: PublishedRoute = {
    method: route.method,
    path: route.path,
    auth: route.auth,
    draft,
    item: route.item,
    summary: route.summary,
    example: route.example,
    contentType: route.contentType ?? "application/json",
  };
  if (route.query) out.query = jsonSchemaOf(route.query, "input");
  if (route.request) out.request = jsonSchemaOf(route.request, "input");
  if (route.response) out.response = jsonSchemaOf(route.response, "output");
  return out;
}

/** The whole published document, shipped routes first and drafts after. */
export function publishedSchema(): PublishedSchema {
  const routes: Record<string, PublishedRoute> = {};
  for (const route of SHIPPED_ROUTES) routes[routeKey(route)] = publish(route, false);
  for (const route of DRAFT_ROUTES) {
    const key = routeKey(route);
    if (!(key in routes)) routes[key] = publish(route, true);
  }
  return {
    $comment:
      "Kodukeel API v1 (ADR-029). Generated by `npm run api:schema` from lib/api/contract.ts and lib/api/draft.ts; do not edit. "
      + "A route marked draft may still change. A response may gain fields within v1, so a client ignores fields it does not know.",
    version: API_VERSION,
    buildHeader: BUILD_HEADER,
    errors: {
      codes: Object.fromEntries(API_ERROR_CODES.map((code) => [code, API_ERROR_STATUS[code]])),
      body: jsonSchemaOf(ApiErrorBody, "output"),
    },
    routes,
  };
}

/** The file as `npm run api:schema` writes it, byte for byte. */
export function publishedSchemaText(): string {
  return `${JSON.stringify(publishedSchema(), null, 2)}\n`;
}
